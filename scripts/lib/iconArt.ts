/** Planche RGBA d'une ligne, une case de 16×16 par icône, dans l'ordre d'ICON_NAMES. */
export function paintIconSheet(): { rgba: Uint8Array; width: number; height: number } {
  const width = ICON_NAMES.length * ICON_SIZE;
  const height = ICON_SIZE;
  const rgba = new Uint8Array(width * height * 4);
  ICON_NAMES.forEach((name, col) => {
    const rows = ART[name];
    if (rows.length > ICON_SIZE) throw new Error(`icône ${name} : ${rows.length} lignes`);
    rows.forEach((line, y) => {
      if (line.length > ICON_SIZE) throw new Error(`icône ${name}, ligne ${y} : ${line.length} colonnes`);
      [...line].forEach((ch, x) => {
        if (ch === '.') return;
        const c = ICON_PALETTE[ch];
        if (!c) throw new Error(`icône ${name} : couleur « ${ch} » inconnue`);
        const o = (y * width + col * ICON_SIZE + x) * 4;
        rgba.set(c, o);
      });
    });
  });
  return { rgba, width, height };
}
